def get_condition(key: str) -> dict:
    """Возвращает настройки группы по ключу, с проверкой."""
    if key not in CONDITIONS:
        raise ValueError(
            f"Неизвестная группа: {key!r}. Доступно: {list(VALID_CONDITIONS)}"
        )
    return CONDITIONS[key]
