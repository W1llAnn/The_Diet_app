def _has_word(n: str, words: list[str]) -> bool:
    """Ищет слова как ОТДЕЛЬНЫЕ токены (по началу слова), а не подстроки.

    Решает проблему «rye» в «broilers/drumstick», «nut» в «donut» и т.п.
    Ищем так, чтобы слово было началом токена: перед ним идёт не-латиница
    (или начало строки). Окончания (apples, beans) разрешены — главное,
    чтобы корень был отдельным словом, а не подстрокой другого слова.

    Русские корни (творог, молок) ищутся подстрокой — окончания многообразны.
    """
    for w in words:
        if not w:
            continue
        # Английский корень (только латиница, >=3 символов).
        if re.fullmatch(r"[a-z]+", w) and len(w) >= 3:
            # Перед корнем не должно быть латинской буквы (борьба с rye в broilers).
            if re.search(r"(^|[^a-z])" + re.escape(w), n):
                return True
        else:
            # Русский корень/фрагмент — подстрокой.
            if w in n:
                return True
    return False


def classify(name: str) -> str:
    """Определяет категорию продукта по названию.

    Возвращает название категории из GROUPS. Если ничего не подошло —
    'Региональные блюда' (заглушка, чтобы не терять продукт).

    ПОРЯДОК ВАЖЕН (от специфичного к общему):
      1) Готовые десерты/сладости/выпечка — ПЕРВЫМИ. Торт со сметаной это торт,
         а не молочное. Брауни с бананом это десерт, а не фрукт.
      2) Картофель, соки, напитки.
      3) Молочные (сладкие/несладкие) — по маркерам вкуса.
      4) Остальные по RULES.
    """
    if not name or not isinstance(name, str):
        return "Региональные блюда"
    n = name.lower()

    # 1) Готовые сладости/десерты/выпечка — 最高 приоритет.
    #    Эти категории ВСЕГДА вреднее для диабета, чем кажется по ингредиенту.
    if _has_word(n, [
        # маркеры готового десерта/выпечки
        "брауни", "brownie", "трайфл", "trifle", "десерт", "dessert", "пудинг",
        "pudding", "мусс", "mousse", "суфле", "тирамис", "чизкейк", "cheesecake",
        "торт", "cake", "пирожн", "пирог", "pie", "кекс", "muffin", "маффин",
        "рулет", "печенье", "cookie", "biscuit", "вафл", "waffle", "пряник",
        "круассан", "пончик", "donut", "бисквит", "кекс",
        # конфеты/сладости
        "конфет", "шоколад", "candy", "chocolate", "мармелад", "зефир", "пастил",
        "халва", "нуга", "карамел", "батончик", "глазир", "морожен", "ice cream",
        # сахар/сиропы/мёд
        "сахар", "sugar", "мёд", "honey", "сироп", "syrup", "сгущён", "сгущен",
        "condensed", "джем", "повидл", "варенье", "jam",
    ]):
        return "Сладости и снеки"

    # 2) Картофель — раньше овощей
    if _has_word(n, ["картофель", "картошка", "potato", "картоф", "фри", "chips"]):
        return "Картофель"

    # 3) КРУПЫ/ЗЕРНО — проверяем ДО соков, напитков и молочных!
    #    Каша на молоке = крупа, не молоко. Рисовая каша с соком = крупа, не сок.
    #    Это критично для диабета: рисовая каша имеет ГИ риса (~75), а не молока (~30).
    is_grain = _has_word(n, [
        "рис", "rice", "гречк", "греч", "buckwheat", "овсян", "овёс", "oat",
        "пшен", "millet", "манн", "кускус", "couscous", "перлов", "barley",
        "ячмен", "булгур", "bulgur", "киноа", "quinoa", "кукуруз", "corn",
        "пшенич", "wheat", "каша ", "каша,", "каша;", "хлопья", "мюсли", "muesli",
        "cereal", "зерно", "крупа", "semolina", "семолин",
    ])
    if is_grain:
        # Различаем белые (рафинированные, ГИ~75) и цельные (ГИ~50).
        if _has_word(n, [
            "белый", "white", "шлиф", "polished", "очищен", "refined",
        ]):
            return "Крупы белые (рафинированные)"
        if _has_word(n, [
            "бурый", "коричнев", "brown", "цельнозерн", "whole grain",
            "whole wheat", "дикий", "wild", "нешлиф", "нешелуш",
        ]):
            return "Крупы цельные"
        # просто «рис»/манка/кускус без уточнения = белые (ГИ высокий).
        if _has_word(n, ["рис", "rice", "манн", "кускус", "couscous"]):
            return "Крупы белые (рафинированные)"
        if _has_word(n, ["греч", "овсян", "овёс", "oat", "перлов", "ячмен",
                         "булгур", "киноа", "пшен"]):
            return "Крупы цельные"
        return "Крупы/зерно прочие"

    # 4) Соки — раньше фруктов и напитков (но после круп: «каша с соком» — это каша)
    if _has_word(n, ["сок", "juice", "нектар", "nectar", "фреш"]):
        return "Соки"

    # 5) Газированные/сладкие напитки
    if _has_word(n, [
        "лимонад", "кола", "cola", "газир", "soda", "coke", "pepsi", "спрайт",
        "фанта", "energy", "энергетик", "чай холод", " квас", "kvas", "компот",
        "water", "вода", "минерал", "чай ", "tea ", "кофе ", "coffee",
    ]):
        return "Напитки"

    # 6) Молочные: сладкие vs несладкие (после десертов и круп — только «чистые» молочные)
    is_dairy = _has_word(n, [
        "творог", "творожн", "йогурт", "йогур", "молок", "кефир", "сыр",
        "сливок", "сливоч", "сметан", "ряжен", "простокваш", "milk", "yogurt",
        "cheese", "cream",
    ])
    if is_dairy:
        is_sweet = _has_word(n, [
            "клубничн", "клубнич", "малин", "вишн", "черник", "яблочн", "яблоч",
            "грушев", "груша", "абрикос", "персик", "сладк", "сахар", "джем",
            "повидл", "шоколад", "карамел", "ванильн", "фруктов", "фрукт", "ягодн",
            "ягода", "сгущ", "chocolate", "sugar", "berry", "fruit", "honey",
            "стеви", "сладкий", "десерт", "глазир", "банан", "медов", "мёд",
            "сироп",
        ])
        return "Молочные сладкие" if is_sweet else "Молочные несладкие"

    # 7) Остальные правила — по порядку
    for category, words in RULES:
        if _has_word(n, words):
            return category
    return "Региональные блюда"
