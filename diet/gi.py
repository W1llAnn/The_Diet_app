"""Оценка гликемического индекса продукта по категории + корректировка по составу.

Подход (обоснован исследованием Sydney GI-датасета, см. 04_prepare_gi.py):
    1. Определяем категорию продукта (food_groups.classify).
    2. Берём базовый ГИ категории из gi_by_category.csv.
    3. Корректируем по фактическому составу (сахар/углеводы/клетчатка):
       - продукты с углеводами ≈0 → ГИ ≈0 (мясо, масло, сыр);
       - молочные с высоким сахаром → поднимаем ГИ вверх;
       - много клетчатки → чуть снижаем.

Почему не точный мэтчинг с Sydney: эксперимент показал, что fuzzy-match даёт
много критических ошибок (молоко→сгущёнка, орехи→grapenuts). Категорийный
подход + корректировка надёжнее и покрывает русские названия.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from .food_groups import classify

ROOT = Path(__file__).resolve().parent.parent
GI_CAT_CSV = ROOT / "data" / "processed" / "gi_by_category.csv"

# Загружаем таблицу «категория → базовый ГИ» один раз.
_GI_CAT: dict[str, int] = dict(
    pd.read_csv(GI_CAT_CSV).set_index("category")["gi_base"].astype(int)
)

# Доп. категории без явного ГИ в таблице (ГИ≈0 — белки/жиры без углеводов).
_GI_CAT_DEFAULTS = {
    "Мясо/рыба/яйца (ГИ≈0)": 0,
    "Жиры/масла (ГИ≈0)": 0,
}


def base_gi_for_category(category: str) -> int:
    """Базовый ГИ категории (из gi_by_category.csv или 0 для белково-жировых)."""
    if category in _GI_CAT_DEFAULTS:
        return _GI_CAT_DEFAULTS[category]
    return _GI_CAT.get(category, 50)  # 50 — нейтральный фолбэк (медиана)


def gi_for_product(name: str, carbs_g=None, sugars_g=None, fiber_g=None,
                   fat_g=None, protein_g=None) -> tuple[int, str, str]:
    """Оценивает ГИ продукта. Возвращает (ГИ, категория, источник решения).

    Корректировки:
        - углеводы ≈0 (≤5г/100г) → ГИ ≈ 0 независимо от категории (мясо, масло);
        - молочные сладкие: если сахара > 10г/100г → ГИ = 55-65 (реальный сахар);
        - высокая клетчатка (≥6г) → ГИ -8 (клетчатка замедляет всасывание).
    """
    category = classify(name)
    gi = base_gi_for_category(category)
    reason = f"базовый ГИ категории «{category}»"

    def num(v):
        return v if (v is not None and not pd.isna(v)) else None

    carbs = num(carbs_g)
    sugars = num(sugars_g)
    fiber = num(fiber_g)

    # 1) Продукты почти без углеводов — ГИ ≈ 0 (не повышают глюкозу крови).
    #    Это ловит мясо/рыбу/яйца/сыр/масло даже если категория определилась иначе.
    #    ВАЖНО: не применяем к крахмалистым категориям (картофель/крупы) — у них
    #    в OFF углеводы часто =0 как «нет данных», а не реальный ноль.
    #    Также не применяем, если carbs=0 (это «нет данных» в OFF), только если
    #    carbs реальное число в диапазоне 0.1-5.
    STARCHY = ("Картофель", "Крупы белые (рафинированные)", "Крупы цельные",
               "Крупы/зерно прочие", "Хлеб и выпечка", "Сухие завтраки", "Макароны")
    if (carbs is not None and 0 < carbs <= 5
            and category not in ("Напитки", "Соки") + STARCHY
            and category not in STARCHY):
        gi = 0
        reason = f"углеводов {carbs}г ≤5 → ГИ≈0"
        return gi, category, reason

    # 2) Сладкие молочные: реальный сахар поднимает ГИ (Sydney тут ненадёжно низкий).
    #    «Творог с вареньем»: сахара много → ГИ ~60.
    if category == "Молочные сладкие" and sugars is not None:
        if sugars >= 15:
            gi = 65
            reason = f"молочное сладкое, сахара {sugars}г ≥15 → ГИ 65"
        elif sugars >= 10:
            gi = 55
            reason = f"молочное сладкое, сахара {sugars}г ≥10 → ГИ 55"
        return gi, category, reason

    # 3) Клетчатка замедляет всасывание — немного снижаем ГИ.
    if fiber is not None and fiber >= 6 and gi > 0:
        gi = max(gi - 8, 0)
        reason += f", клетчатка {fiber}г → -8"

    return gi, category, reason


# Метки для диабета по итоговому ГИ.
# Пороги по общепринятой классификации GI: низкий ≤55, средний 56-69, высокий ≥70.
# Дополнительно: явный сахар (≥20г/100г) → «осторожно» даже при низком ГИ.
def diabetes_label(gi: int, sugars_g=None, category: str = "",
                   name: str = "") -> tuple[str, str]:
    """Метка совместимости с диабетом 2 типа.

    Возвращает (категория_метки, основание).
    Метки: 'recommended' / 'allowed' / 'caution' / 'forbidden'
    (рекомендовано / разрешено / с осторожностью / запрещено).

    name — название продукта; используется как запасной сигнал опасности,
    т.к. в OFF sugars_g почти всегда пуст, и «сахар»/«мёд»/«кола» в названии
    сами по себе означают концентрированный сахар.
    """
    def num(v):
        return v if (v is not None and not pd.isna(v)) else None
    sugars = num(sugars_g)

    # -1) МАРКЕРЫ ОПАСНОСТИ ПО НАЗВАНИЮ — раз в OFF sugars_g почти всегда пуст,
    # используем название как сигнал. Это спасает «сахар», «мёд», «колу», «сок».
    if name and isinstance(name, str):
        nl = name.lower()
        # Чистый сахар/мёд/сироп/сгущёнка → запрещено.
        if any(w in nl for w in ["сахар", "sugar", "мёд", "мед ", "honey",
                                  "сироп", "syrup", "сгущён", "сгущен",
                                  "паток", "molasses", "глюкоз", "фруктоз",
                                  "dextrose", "варенье", "джем", "повидл"]):
            return "forbidden", f"«{name[:30]}» — концентрированный сахар"
        # Сладкие газировки (кола/спрайт/фанта/лимонад) → запрещено.
        if any(w in nl for w in ["кола", "cola", "coke", "pepsi", "спрайт",
                                  "фанта", "лимонад", "sprite", "fanta",
                                  "газир", "soda", "энергетик", "energy"]):
            return "forbidden", f"«{name[:30]}» — сладкая газировка"
        # Соки/нектары → осторожно (свободные сахара, нет клетчатки).
        if any(w in nl for w in ["сок", "juice", "нектар", "nectar"]):
            return "caution", f"«{name[:30]}» — сок, свободные сахара"
        # Алкоголь → осторожно (риск гипо при диабете).
        if any(w in nl for w in ["пиво", "beer", "вино", "wine", "водк",
                                  "vodka", "виски", "whisky", "коньяк",
                                  "бренди", "brandy", "ром ", "джин ", "ликёр", "ликер"]):
            return "caution", f"«{name[:30]}» — алкоголь, риск гипогликемии"

    # 0) Сладости и снеки — НИКОГДА не «рекомендовано», минимум «осторожно».
    # Готовые десерты/конфеты/печенье априори проблемны при диабете: в OFF
    # сахар часто не заполнен (=0 или None), но продукт-то сладкий.
    if category == "Сладости и снеки":
        if sugars is not None and sugars >= 30:
            return "forbidden", f"сладости, сахар {sugars}г ≥30 — запрещено"
        if sugars is not None and sugars >= 15:
            return "caution", f"сладости, сахар {sugars}г — осторожно"
        # сахар None или ≤15 — всё равно осторожно: настоящие сладости без
        # сахара почти не бывают, значит данных просто нет.
        return "caution", "категория «Сладости и снеки» — осторожно для диабета"

    # 0a) Соки и сладкие напитки — НИКОГДА не «рекомендовано».
    # Соки содержат свободные сахара (фруктоза), сладкие напитки — добавленный.
    # Даже фреш-соки при диабете ограничивают (нет клетчатки цельного фрукта).
    if category in ("Соки", "Напитки"):
        if sugars is not None and sugars >= 8:
            return "caution", f"{category.lower()}, сахар {sugars}г — осторожно"
        return "allowed", f"{category.lower()}, сахар неизвестен — разрешено (проверьте состав)"

    # 0b) Чистый сахар/мёд/сироп → запрещено. Это концентрированные сахара.
    if category == "Сладости и снеки" or (sugars is not None and sugars >= 50):
        return "forbidden", f"сахара {sugars}г ≥50 — концентрированный сахар, запрещено"

    # 1) Мясо/рыба/яйца — ГИ ≈ 0 независимо от категории (белок+жир, без углеводов).
    #    Ловит «говядину в собственном соку», которая могла попасть в другую категорию.
    if category == "Мясо/рыба/яйца (ГИ≈0)":
        return "allowed", "мясо/рыба/яйца — без углеводов, безопасно"

    # ГИ≈0 и мало сахара — безопасно (сыр, масло, некрахмалистые овощи).
    if gi <= 10:
        return "allowed", f"ГИ {gi} (≈0), сахар {sugars}г — безопасно"

    # Чистый сахар / очень много сахара → запрещено.
    if sugars is not None and sugars >= 40:
        return "forbidden", f"сахар {sugars}г ≥40 — запрещено"
    if sugars is not None and sugars >= 20 and gi >= 50:
        return "caution", f"сахар {sugars}г и ГИ {gi} — осторожно"

    # По ГИ.
    if gi <= 45:
        return "recommended", f"ГИ {gi} ≤45 — низкий, рекомендуется"
    if gi <= 55:
        return "allowed", f"ГИ {gi} ≤55 — низкий, разрешено"
    if gi <= 69:
        return "caution", f"ГИ {gi} (56-69) — средний, осторожно"
    # ГИ ≥70
    # Доп. проверка сахара: варёная морковь/свёкла имеют высокий ГИ, но мало сахара,
    # это не «запрещено», а «осторожно».
    if sugars is not None and sugars <= 8:
        return "caution", f"ГИ {gi} ≥70, но сахара {sugars}г мало → осторожно"
    return "forbidden", f"ГИ {gi} ≥70 и сахар {sugars}г — запрещено"
