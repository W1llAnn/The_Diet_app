-- =====================================================================
-- Vivora: удалить триггер protect_is_admin
-- ---------------------------------------------------------------------
-- Supabase Studio → SQL Editor → New query → вставить → Run.
--
-- Контекст: триггер protect_is_admin блокировал любое изменение is_admin
-- через клиент, но на практике мешал легитимному сохранению профиля:
-- при upsert существующей строки с is_admin=true, если supabase-js трактовал
-- операцию как затрагивающую колонку is_admin, триггер бросал исключение
-- "Изменение is_admin разрешено только через панель Supabase", и сохранение
-- падало с "Не удалось сохранить".
--
-- RLS уже защищает профиль (auth.uid() = id) — никто чужой не поменяет
-- is_admin. Триггер избыточен и вреден, удаляем.
-- =====================================================================

drop trigger if exists protect_is_admin on public.profiles;
drop function if exists public.protect_is_admin();

-- Проверка: триггера больше нет
select tgname from pg_trigger where tgname = 'protect_is_admin';
-- (должно вернуться пусто)
